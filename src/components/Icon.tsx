export type IconName = keyof typeof icons;
export function Icon({
  name,
  size = 18,
  className = '',
}: {
  name: IconName;
  size?: number;
  className?: string;
}) {
  const Component = icons[name];
  return <Component size={size} strokeWidth={1.65} className={className} aria-hidden="true" />;
}
